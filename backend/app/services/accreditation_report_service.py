import csv
import io
from datetime import datetime
from typing import Dict, Any, List, Optional
from sqlalchemy.orm import Session
from backend.app.models.models import InstitutionalReport, AuditLogEntry
from backend.app.services.institutional_intelligence_service import InstitutionalIntelligenceService
from backend.app.services.audit_service import AuditService


class AccreditationReportService:
    DISCLAIMER = (
        "Generated from actual institutional records in ProofHire. ProofHire is not officially certified or endorsed "
        "by NAAC or NIRF, and no synthetic rankings or compliance scores are generated."
    )

    @staticmethod
    def generate_report(
        db: Session,
        college_id: str,
        report_type: str = "NAAC_NIRF_PLACEMENT",
        reporting_period: str = "2025-2026",
        generated_by: str = "T&P Officer",
        actor_role: str = "officer",
    ) -> InstitutionalReport:
        if actor_role not in ["officer", "university_admin"]:
            raise PermissionError("Unauthorized: Only placement officers or university admins can generate institutional reports.")

        overview = InstitutionalIntelligenceService.get_institutional_overview(
            db, college_id, reporting_period=reporting_period
        )
        placement = InstitutionalIntelligenceService.get_placement_performance_analytics(db, college_id)
        demand = InstitutionalIntelligenceService.get_industry_skill_demand(db, college_id)

        audit_refs = [
            a.id
            for a in db.query(AuditLogEntry)
            .filter(AuditLogEntry.college_id == college_id)
            .order_by(AuditLogEntry.id.desc())
            .limit(10)
            .all()
        ]

        metrics_bundle = {
            "overview_kpis": overview["kpis"],
            "placement_funnel": placement["funnel"],
            "conversions": placement["conversions"],
            "department_outcomes": placement["department_outcomes"],
            "top_skill_demands": demand["approved_skill_demand"][:5],
            "sources": {
                "student_counts": "students table",
                "competency_coverage": "competencies + evidence tables",
                "placement_funnel": "applications + selection_decisions tables",
            },
        }

        report = InstitutionalReport(
            college_id=college_id,
            report_type=report_type,
            reporting_period=reporting_period,
            generated_by=generated_by,
            metrics_json=metrics_bundle,
            missing_data_warnings=overview["data_quality_warnings"],
            evidence_references=audit_refs,
            disclaimer=AccreditationReportService.DISCLAIMER,
        )
        db.add(report)
        db.commit()
        db.refresh(report)

        AuditService.log_event(
            db=db,
            college_id=college_id,
            actor=generated_by,
            action=f"Generated institutional report {report_type} for period {reporting_period} (ID: {report.id})",
        )
        return report

    @staticmethod
    def list_reports(db: Session, college_id: str) -> List[Dict[str, Any]]:
        rows = (
            db.query(InstitutionalReport)
            .filter(InstitutionalReport.college_id == college_id)
            .order_by(InstitutionalReport.created_at.desc())
            .all()
        )
        return [
            {
                "id": r.id,
                "college_id": r.college_id,
                "report_type": r.report_type,
                "reporting_period": r.reporting_period,
                "generated_by": r.generated_by,
                "metrics": r.metrics_json,
                "missing_data_warnings": r.missing_data_warnings,
                "evidence_references": r.evidence_references,
                "disclaimer": r.disclaimer,
                "created_at": r.created_at.isoformat() if r.created_at else None,
            }
            for r in rows
        ]

    @staticmethod
    def export_report_csv(db: Session, report_id: str, college_id: str) -> str:
        report = (
            db.query(InstitutionalReport)
            .filter(InstitutionalReport.id == report_id, InstitutionalReport.college_id == college_id)
            .first()
        )
        if not report:
            raise ValueError("Report not found in college")

        buf = io.StringIO()
        writer = csv.writer(buf)
        writer.writerow(["Report ID", report.id])
        writer.writerow(["College ID", report.college_id])
        writer.writerow(["Report Type", report.report_type])
        writer.writerow(["Reporting Period", report.reporting_period])
        writer.writerow(["Generated By", report.generated_by])
        writer.writerow(["Generated At", report.created_at.isoformat() if report.created_at else ""])
        writer.writerow([])
        writer.writerow(["Metric", "Value"])
        for k, v in (report.metrics_json.get("overview_kpis", {}) or {}).items():
            writer.writerow([k, v])
        writer.writerow([])
        writer.writerow(["Disclaimer", report.disclaimer])
        return buf.getvalue()

    @staticmethod
    def export_report_pdf_bytes(db: Session, report_id: str, college_id: str) -> bytes:
        report = (
            db.query(InstitutionalReport)
            .filter(InstitutionalReport.id == report_id, InstitutionalReport.college_id == college_id)
            .first()
        )
        if not report:
            raise ValueError("Report not found in college")

        kpis = report.metrics_json.get("overview_kpis", {})
        lines = [
            f"ProofHire Institutional Report: {report.report_type}",
            f"College: {report.college_id} | Period: {report.reporting_period}",
            f"Generated By: {report.generated_by}",
            f"Total Students: {kpis.get('total_registered_students', 0)}",
            f"Verified Coverage: {kpis.get('verified_skill_coverage_pct', 0)}%",
            f"Applications: {kpis.get('applications_submitted', 0)} | Selected: {kpis.get('students_selected', 0)}",
            "Note: Derived strictly from institutional DB records; not NAAC/NIRF certified.",
        ]
        text_ops = "\\n".join(lines).replace("(", "[").replace(")", "]")
        stream_content = f"BT /F1 11 Tf 50 750 Td ({text_ops}) Tj ET"
        pdf = (
            "%PDF-1.4\n"
            "1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj\n"
            "2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj\n"
            "3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >> endobj\n"
            f"4 0 obj << /Length {len(stream_content)} >> stream\n{stream_content}\nendstream endobj\n"
            "5 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj\n"
            "xref\n0 6\n0000000000 65535 f \n0000000010 00000 n \n0000000060 00000 n \n0000000117 00000 n \n0000000240 00000 n \n0000000400 00000 n \n"
            "trailer << /Size 6 /Root 1 0 R >>\nstartxref\n468\n%%EOF\n"
        )
        return pdf.encode("latin-1", errors="replace")
